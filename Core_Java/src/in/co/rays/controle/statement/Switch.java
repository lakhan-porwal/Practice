package in.co.rays.controle.statement;

public class Switch {
	public static void main(String[] ags) {

		int day = 3;

		switch (day) {

		case 1:
			System.out.println("Monday");
			break;
		case 2:
			System.out.println("Tuesday");
			break;
		case 3:
			System.out.println("Wednesday");
			break;
		default:
			System.out.println("Invalid day");

		}

	}
}
